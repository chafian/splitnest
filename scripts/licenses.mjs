// Writes THIRD_PARTY_LICENSES.md from the installed direct dependencies.
// Usage: node scripts/licenses.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
// Code that ships inside the packaged app (bundled into the renderer or unpacked).
const editor = Object.keys(pkg.devDependencies).filter((n) => n.startsWith('@codemirror/') || n.startsWith('@lezer/'));
const shipped = ['node-pty', 'react', 'react-dom', 'scheduler', '@xterm/xterm', '@xterm/addon-fit', '@xterm/addon-search', '@xterm/addon-unicode11', '@xterm/addon-web-links', '@xterm/addon-webgl', ...editor, 'material-icon-theme', 'electron'];

function info(name) {
  const p = JSON.parse(readFileSync(path.join(root, 'node_modules', name, 'package.json'), 'utf8'));
  const repo = typeof p.repository === 'string' ? p.repository : p.repository?.url ?? '';
  return { name, version: p.version, license: p.license ?? 'see package', repo: repo.replace(/^git\+/, '').replace(/\.git$/, '') };
}

const row = (d) => `| ${d.name} | ${d.version} | ${d.license} | ${d.repo} |`;
const header = '| Package | Version | License | Source |\n|---|---|---|---|';
const dev = Object.keys(pkg.devDependencies).filter((n) => !shipped.includes(n)).sort();

const md = `# Third-party software

Generated by \`node scripts/licenses.mjs\` from installed packages. Versions are pinned in \`package.json\` / \`package-lock.json\`.

## Shipped in the packaged application

${header}
${shipped.map((n) => row(info(n))).join('\n')}

Electron bundles Chromium and Node.js. Their licenses are distributed with every packaged build as \`LICENSE\` and \`LICENSES.chromium.html\` in the application folder.
developer-icons (MIT, Copyright (c) 2024 Sandesh Katwal aka xandemon, https://github.com/xandemon/developer-icons): five logo SVGs in \`src/renderer/assets/agent-icons/\` (Claude, OpenAI, Gemini, GitHub Copilot, Cursor), copied unchanged with its license, to identify AI agent CLIs in terminal tabs. The logos are trademarks of their owners.
Tabler Icons (MIT, Copyright (c) 2020-2026 Paweł Kuna, https://github.com/tabler/tabler-icons): the UI icons. A subset of \`@tabler/icons\` (a build-time dependency) is generated into \`src/renderer/components/tabler/icons.generated.ts\` by \`npm run ui-icons\` and compiled into the renderer; its MIT license is included there.
Material Icon Theme: only the SVG subset in \`src/renderer/assets/file-icons/\` is bundled (copied by \`npm run icons\`; its MIT license is included there).
CodeMirror's packages pull in further MIT-licensed \`@lezer/*\` parsers, \`style-mod\`, \`w3c-keyname\` and \`crelt\`, which are bundled into the renderer as well.
node-pty also ships Microsoft's \`conpty.dll\` and \`OpenConsole.exe\` (from Windows Terminal, MIT License) and \`winpty\` (MIT License) in its prebuilds.

## Build, test and development tools (not shipped)

${header}
${dev.map((n) => row(info(n))).join('\n')}

Transitive dependencies are recorded in \`package-lock.json\`; run \`npx license-checker --summary\` (not installed by default) for a full transitive report.
`;
writeFileSync(path.join(root, 'THIRD_PARTY_LICENSES.md'), md);
console.log('wrote THIRD_PARTY_LICENSES.md');
