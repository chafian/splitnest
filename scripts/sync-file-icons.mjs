// Copies only the Material Icon Theme SVGs referenced by
// src/renderer/features/explorer/icon-map.json into the renderer assets, so
// the app bundles a small, explicit subset. Unknown icon names fail the run.
// Usage: node scripts/sync-file-icons.mjs
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const source = path.join(root, 'node_modules', 'material-icon-theme', 'icons');
const target = path.join(root, 'src', 'renderer', 'assets', 'file-icons');
const map = JSON.parse(readFileSync(path.join(root, 'src', 'renderer', 'features', 'explorer', 'icon-map.json'), 'utf8'));
const pkg = JSON.parse(readFileSync(path.join(root, 'node_modules', 'material-icon-theme', 'package.json'), 'utf8'));

const names = new Set([
  map.defaultFile,
  map.defaultFolder,
  ...Object.values(map.fileNames),
  ...map.filePatterns.map(([, icon]) => icon),
  ...Object.values(map.extensions),
  ...Object.values(map.folderNames),
]);
const missing = [...names].filter((n) => !existsSync(path.join(source, `${n}.svg`)));
if (missing.length) {
  console.error(`Unknown icons in icon-map.json (not in material-icon-theme ${pkg.version}):\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
for (const n of [...names].sort()) copyFileSync(path.join(source, `${n}.svg`), path.join(target, `${n}.svg`));
copyFileSync(path.join(root, 'node_modules', 'material-icon-theme', 'LICENSE'), path.join(target, 'LICENSE'));
writeFileSync(
  path.join(target, 'README.md'),
  `Icons from [Material Icon Theme](https://github.com/material-extensions/vscode-material-icon-theme) ${pkg.version} (MIT License, see LICENSE).\nGenerated by \`npm run icons\`; do not edit by hand.\n`,
);
console.log(`copied ${names.size} icons (of ${readdirSync(source).length}) from material-icon-theme ${pkg.version}`);
