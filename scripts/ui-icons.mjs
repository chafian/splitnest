// Generates src/renderer/components/tabler/icons.generated.ts: the UI icons SplitNest uses,
// taken from the pinned @tabler/icons package (MIT, https://github.com/tabler/tabler-icons).
// Only the icons listed here are copied; nothing from the package ships otherwise.
// Usage: npm run ui-icons
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const pkgDir = path.join(root, 'node_modules', '@tabler', 'icons');
const version = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const outline = JSON.parse(readFileSync(path.join(pkgDir, 'tabler-nodes-outline.json'), 'utf8'));
const filled = JSON.parse(readFileSync(path.join(pkgDir, 'tabler-nodes-filled.json'), 'utf8'));

/** SplitNest icon name -> Tabler icon (outline unless marked filled). */
const MAP = {
  plus: 'plus',
  folder: 'folder',
  folderPlus: 'folder-plus',
  splitRight: 'layout-columns',
  splitDown: 'layout-rows',
  close: 'x',
  search: 'search',
  restart: 'refresh',
  play: 'player-play',
  settings: 'settings',
  keyboard: 'keyboard',
  sidebar: 'layout-sidebar',
  terminal: 'terminal-2',
  warning: 'alert-triangle',
  pencil: 'pencil',
  trash: 'trash',
  chevronDown: 'chevron-down',
  chevronUp: 'chevron-up',
  chevronRight: 'chevron-right',
  closePane: 'square-x',
  collapse: 'square-minus',
  files: 'files',
  command: 'command',
  dot: { name: 'point', filled: true },
  check: 'check',
  stop: 'player-stop',
  home: 'home',
  focus: 'maximize',
  maximize: 'arrows-diagonal',
  restoreLayout: 'arrows-diagonal-minimize-2',
  more: 'dots',
  bell: 'bell',
  gitBranch: 'git-branch',
};

const camel = (k) => k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const entries = Object.entries(MAP).map(([ours, spec]) => {
  const { name, filled: isFilled } = typeof spec === 'string' ? { name: spec, filled: false } : spec;
  const nodes = (isFilled ? filled : outline)[name];
  if (!nodes) throw new Error(`Tabler icon not found: ${name}${isFilled ? ' (filled)' : ''}`);
  // Only plain geometry attributes are kept; anything else (e.g. styling) is dropped.
  const allowed = new Set(['d', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'x1', 'x2', 'y1', 'y2', 'width', 'height', 'points']);
  const clean = nodes.map(([tag, attrs]) => {
    if (!['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'].includes(tag)) throw new Error(`unexpected element <${tag}> in ${name}`);
    return [tag, Object.fromEntries(Object.entries(attrs).filter(([k]) => allowed.has(k)).map(([k, v]) => [camel(k), String(v)]))];
  });
  return `  ${ours}: { tabler: '${name}', filled: ${isFilled}, nodes: ${JSON.stringify(clean)} },`;
});

const outDir = path.join(root, 'src', 'renderer', 'components', 'tabler');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  path.join(outDir, 'icons.generated.ts'),
  `// Generated by scripts/ui-icons.mjs from @tabler/icons ${version}. Do not edit by hand.
// Tabler Icons: MIT License, Copyright (c) 2020-2026 Paweł Kuna (see LICENSE in this folder).
export type IconNode = [tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline' | 'polygon' | 'ellipse', attrs: Record<string, string>];

export const TABLER_VERSION = '${version}';

export const ICONS = {
${entries.join('\n')}
} satisfies Record<string, { tabler: string; filled: boolean; nodes: IconNode[] }>;
`,
);
copyFileSync(path.join(pkgDir, 'LICENSE'), path.join(outDir, 'LICENSE'));
console.log(`wrote ${Object.keys(MAP).length} Tabler ${version} icons to src/renderer/components/tabler/`);
